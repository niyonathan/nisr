"""Fit, validate and summarise the yield models; write public outputs and the model bundle.

    python analysis/yield_model.py

Needs data/processed/plot_crops.parquet (run pipeline.py first).
"""
import json
import sys
from pathlib import Path

import joblib
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from agri import model as m  # noqa: E402
from agri.io import PROCESSED_DIR, PUBLIC_DIR  # noqa: E402

MODELS_DIR = ROOT / "models"
REPORTS_DIR = ROOT / "reports"


def district_yield_gaps() -> pd.DataFrame:
    """How far each district's typical yield sits below what the better national farms achieve."""
    national = pd.read_csv(PUBLIC_DIR / "crop_yields_national.csv").set_index("crop")
    district = pd.read_csv(PUBLIC_DIR / "crop_yields_district.csv")
    district["national_p75_kg_ha"] = district["crop"].map(national["yield_p75_kg_ha"])
    district["gap_to_national_p75_pct"] = 1 - district["yield_median_kg_ha"] / district["national_p75_kg_ha"]
    cols = ["province", "district", "crop", "n_obs", "yield_median_kg_ha", "national_p75_kg_ha",
            "gap_to_national_p75_pct", "improved_seed_rate", "inorganic_fertilizer_rate", "irrigated_rate"]
    return district[cols].sort_values(["crop", "gap_to_national_p75_pct"], ascending=[True, False])


def pct(x: float) -> str:
    return f"{x:+.0%}"


def write_report(metrics: dict, per_crop: pd.DataFrame, assoc: pd.DataFrame, importance: pd.DataFrame,
                 scenario: pd.DataFrame) -> str:
    sig = assoc[assoc["significant"]]
    lines = [
        "# Yield model results",
        "",
        "Generated by `analysis/yield_model.py` from NISR AHS 2024 microdata.",
        "",
        "## Data",
        "",
        f"- {metrics['n_obs']:,} crop-on-plot records with a valid yield, {metrics['n_crops']} crops "
        f"with at least {m.MIN_RECORDS_PER_CROP} records each.",
        "- Outcome: log yield (kg/ha). Yield = harvest ÷ (plot area × crop's share of the plot).",
        "",
        "## 1. Which practices go with higher yields?",
        "",
        "One regression per crop: log yield on each practice, controlling for plot size, crop share, "
        "number of crops on the plot, soil threats, household head sex and household size, with district "
        "and season fixed effects. Standard errors are clustered by survey cluster. Effects are the % "
        "difference in yield between plots that use the practice and similar plots that don't.",
        "",
        "These are **associations** in survey data. Farmers who use fertilizer may also differ in ways "
        "the survey does not record (soil quality, skills), so the numbers show where yields are higher, "
        "not a guaranteed result of adopting a practice.",
        "",
        "Statistically significant associations (p < 0.05):",
        "",
        "| Crop | Practice | Plots using it | Yield difference | 95% CI |",
        "|---|---|---:|---:|---|",
    ]
    for r in sig.itertuples():
        lines.append(f"| {r.crop} | {r.practice_label} | {r.n_users:,} | {pct(r.effect_pct)} | "
                     f"{pct(r.ci_low_pct)} to {pct(r.ci_high_pct)} |")
    lines += [
        "",
        "**Reading the irrigation results.** Only about 3% of modelled plots are irrigated, mostly "
        "Season C vegetables and marshland rice, so irrigated and rain-fed plots of the same crop are "
        "not comparable. The negative coefficients for beans and rice reflect where and when irrigation "
        "is used, not irrigation lowering yields. The platform therefore treats irrigation as a "
        "planning question (where water is missing or unaffordable) rather than a yield-effect claim.",
        "",
        "## 2. Yield predictor",
        "",
        "Gradient-boosted trees (scikit-learn `HistGradientBoostingRegressor`) on log yield, one model "
        f"for all {metrics['n_crops']} crops, with {len(m.FEATURES)} features: crop, district, season, "
        "seed, fertilizer type and rate, pesticide, irrigation status, soil conservation, land tenure, "
        "and household characteristics. Every tree leaf summarises at least 50 plots.",
        "",
        f"Validated with {metrics['folds']}-fold cross-validation grouped by survey cluster, against a "
        "benchmark that predicts the median yield of the same crop in the same district.",
        "",
        "| | R² (log yield) | Median absolute error |",
        "|---|---:|---:|",
        f"| Benchmark: crop × district median | {metrics['baseline_crop_district_median']['r2_log']:.2f} | "
        f"{metrics['baseline_crop_district_median']['median_abs_pct_error']:.0%} |",
        f"| Yield predictor | {metrics['model']['r2_log']:.2f} | {metrics['model']['median_abs_pct_error']:.0%} |",
        "",
        f"The model beats the benchmark for all {len(per_crop)} crops "
        f"(within-crop R² {per_crop['r2_log_model'].min():.2f}–{per_crop['r2_log_model'].max():.2f}). "
        "Single-plot predictions remain uncertain, because weather, pests and soil quality are not in the "
        "survey, so the app presents expected ranges and comparisons with similar farms, not exact forecasts.",
        "",
        "Most important features (drop in R² when shuffled):",
        "",
        "| Feature | Importance |",
        "|---|---:|",
    ]
    for r in importance.head(12).itertuples():
        lines.append(f"| {r.feature} | {r.importance_r2_drop:.3f} |")
    top = (scenario[scenario["share_without_inputs"] > 0.5]
           .sort_values("scenario_gain_pct", ascending=False).head(10))
    lines += [
        "",
        "## 3. Input scenario",
        "",
        "For each district and crop, the predictor estimates average yield if plots lacking improved seed "
        "or inorganic fertilizer adopted them, at the median fertilizer rate of users of that crop. An input "
        f"is included only for crops where at least {m.MIN_ADOPTION_FOR_SCENARIO:.0%} of plots (and "
        f"{m.MIN_GROUP_SIZE}+) already use it, so the model never borrows patterns from other crops. "
        "This is what the model expects for similar plots, not a promised gain.",
        "",
        "Largest model-estimated gains where most plots currently lack these inputs:",
        "",
        "| District | Crop | Plots lacking inputs | Predicted kg/ha | Scenario kg/ha | Change |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for r in top.itertuples():
        lines.append(f"| {r.district} | {r.crop} | {r.share_without_inputs:.0%} | {r.predicted_kg_ha:,.0f} | "
                     f"{r.scenario_kg_ha:,.0f} | {pct(r.scenario_gain_pct)} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    for d in (MODELS_DIR, REPORTS_DIR, PUBLIC_DIR):
        d.mkdir(parents=True, exist_ok=True)
    data = m.prepare(pd.read_parquet(PROCESSED_DIR / "plot_crops.parquet"))
    print(f"Modelling {len(data):,} records, {data['crop'].nunique()} crops")

    print("Practice associations ...")
    assoc = m.practice_associations(data)
    print("Cross-validation ...")
    metrics, per_crop = m.cross_validate(data)
    print("Final model, importance and scenarios ...")
    bundle = m.fit_predictor(data)
    importance = m.feature_importance(bundle, data)
    scenario = m.input_scenario(bundle, data)
    gaps = district_yield_gaps()

    bundle["metrics"] = metrics
    bundle["fertilizer_kg_ha_median"] = (
        data[data["inorganic_fertilizer"] == 1].groupby("crop")["fertilizer_kg_ha"].median().to_dict()
    )
    joblib.dump(bundle, MODELS_DIR / "yield_model.joblib", compress=3)

    assoc.round(4).to_csv(PUBLIC_DIR / "practice_associations.csv", index=False)
    per_crop.round(4).to_csv(PUBLIC_DIR / "model_metrics_by_crop.csv", index=False)
    importance.round(4).to_csv(PUBLIC_DIR / "feature_importance.csv", index=False)
    scenario.round(4).to_csv(PUBLIC_DIR / "input_scenario_district.csv", index=False)
    gaps.round(4).to_csv(PUBLIC_DIR / "district_yield_gaps.csv", index=False)
    (PUBLIC_DIR / "model_metrics.json").write_text(json.dumps(metrics, indent=2, default=float))
    (REPORTS_DIR / "yield_model.md").write_text(write_report(metrics, per_crop, assoc, importance, scenario))

    print(f"R² log yield: model {metrics['model']['r2_log']:.3f} vs "
          f"benchmark {metrics['baseline_crop_district_median']['r2_log']:.3f}")
    print(f"Significant practice associations: {int(assoc['significant'].sum())} of {len(assoc)}")
    print(f"Model saved: {MODELS_DIR / 'yield_model.joblib'} "
          f"({(MODELS_DIR / 'yield_model.joblib').stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
